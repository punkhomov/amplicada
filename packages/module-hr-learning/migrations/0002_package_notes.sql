-- Замечания к принятому пакету: что пропущено при распаковке и на что жаловался разбор.
--
-- Отдельно от `error`, и это не косметика: `error` означает «пакет не принят», а здесь пакет как раз
-- принят — просто неполностью или с оговорками. Свалить их в одну колонку значило бы либо потерять
-- замечания у готового пакета, либо показывать «Ошибка» там, где курс работает.
--
-- Без этой колонки пропущенные файлы и предупреждения разбора видел только лог: админ на карточке
-- получал «Готов» и не знал, что из его пакета выкинули полтора десятка файлов.
ALTER TABLE "hr_learning"."packages" ADD COLUMN IF NOT EXISTS "notes" jsonb NOT NULL DEFAULT '[]'::jsonb;
