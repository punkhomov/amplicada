/**
 * Заголовки раздачи контента курса — и решение об изоляции, которое за ними стоит.
 *
 * **Курс раздаётся с нашего origin и без песочницы.** То есть чужой JS внутри пакета работает с
 * правами вошедшего: `fetch('/api/...')` из курса уйдёт с cookie сессии. Это осознанный выбор, а не
 * недосмотр, и так устроено большинство LMS (Moodle в том числе).
 *
 * Почему не изолировали. Механизм поиска API в SCORM — это обход окон: курс смотрит `window`, потом
 * `parent`, `top`, `opener`, `opener.top`, пока не найдёт `API` (1.2) или `API_1484_11` (2004).
 * Обход работает только внутри одного origin: на первом же чужом окне драйвер получает
 * SecurityError и **сдаётся**, а не пробует дальше. Любая изоляция, разрывающая same-origin, ломает
 * поиск для всех пакетов, кроме тех, что находят API в собственном окне. Storyline к ним не
 * относится: он открывает курс отдельным окном и ищет API через открывшую страницу.
 *
 * Проверено на живом пакете: то же содержимое открывается напрямую и работает, а в iframe нашей
 * страницы — нет, и разница ровно одна — появился cross-origin родитель. Ни `allow-same-origin`, ни
 * `allow-popups-to-escape-sandbox` этого не лечат: дело не в разрешениях песочницы, а в том, что
 * над содержимым оказалось чужое окно.
 *
 * Изоляцию можно вернуть, но не настройкой заголовков, а сменой модели запуска: отдельный хост
 * **плюс** открытие курса своей вкладкой, без обрамления нашей страницей (так делает SCORM Cloud).
 * Тогда чужого окна над курсом нет и обход работает. Это отдельная работа — план
 * `ref/plans/2026-08-11-content-isolation.md`.
 */

/**
 * `Content-Security-Policy` для файлов пакета.
 *
 * `sandbox` здесь нет — см. выше. `frame-ancestors 'self'` осмыслен ровно потому, что песочницы
 * нет: origin у документа настоящий, и директива делает то, что написано, — запрещает встраивать
 * наш контент чужим сайтам. В песочнице она запрещала бы вообще любое встраивание, включая наше,
 * потому что `'self'` не совпадает с обезличенным origin.
 */
export function contentSecurityPolicy(): string {
  return "frame-ancestors 'self'";
}
